`timescale 1ns/1ps

module systolic_array_tb;

    parameter DATA_WIDTH = 8;
    parameter ACC_WIDTH  = 32;

    reg clk;
    reg rst;
    reg enable;

    reg signed [DATA_WIDTH-1:0] A0, A1, A2, A3;
    reg signed [DATA_WIDTH-1:0] B0, B1, B2, B3;

    wire signed [ACC_WIDTH-1:0] sum00, sum01, sum02, sum03;
    wire signed [ACC_WIDTH-1:0] sum10, sum11, sum12, sum13;
    wire signed [ACC_WIDTH-1:0] sum20, sum21, sum22, sum23;
    wire signed [ACC_WIDTH-1:0] sum30, sum31, sum32, sum33;

    //============================================================
    // DUT
    //============================================================

    systolic_array uut (

        .clk(clk),
        .rst(rst),
        .enable(enable),

        .A0(A0),
        .A1(A1),
        .A2(A2),
        .A3(A3),

        .B0(B0),
        .B1(B1),
        .B2(B2),
        .B3(B3),

        .sum00(sum00),
        .sum01(sum01),
        .sum02(sum02),
        .sum03(sum03),

        .sum10(sum10),
        .sum11(sum11),
        .sum12(sum12),
        .sum13(sum13),

        .sum20(sum20),
        .sum21(sum21),
        .sum22(sum22),
        .sum23(sum23),

        .sum30(sum30),
        .sum31(sum31),
        .sum32(sum32),
        .sum33(sum33)
    );

    //============================================================
    // Clock
    //============================================================

    initial
        clk = 0;

    always
        #5 clk = ~clk;

    //============================================================
    // Stimulus
    //============================================================

    initial begin

        $dumpfile("systolic_array_tb.vcd");
        $dumpvars(0, systolic_array_tb);

        rst = 1;
        enable = 0;

        A0 = 0; A1 = 0; A2 = 0; A3 = 0;
        B0 = 0; B1 = 0; B2 = 0; B3 = 0;

        #20;

        rst = 0;
        enable = 1;

        //--------------------------------------------------------
        // Cycle 0
        //--------------------------------------------------------
        @(posedge clk);
        A0<=1;   A1<=0;   A2<=0;   A3<=0;
        B0<=17;  B1<=0;   B2<=0;   B3<=0;

        //--------------------------------------------------------
        // Cycle 1
        //--------------------------------------------------------
        @(posedge clk);
        A0<=2;   A1<=5;   A2<=0;   A3<=0;
        B0<=21;  B1<=18;  B2<=0;   B3<=0;

        //--------------------------------------------------------
        // Cycle 2
        //--------------------------------------------------------
        @(posedge clk);
        A0<=3;   A1<=6;   A2<=9;   A3<=0;
        B0<=25;  B1<=22;  B2<=19;  B3<=0;

        //--------------------------------------------------------
        // Cycle 3
        //--------------------------------------------------------
        @(posedge clk);
        A0<=4;   A1<=7;   A2<=10;  A3<=13;
        B0<=29;  B1<=26;  B2<=23;  B3<=20;

        //--------------------------------------------------------
        // Cycle 4
        //--------------------------------------------------------
        @(posedge clk);
        A0<=0;   A1<=8;   A2<=11;  A3<=14;
        B0<=0;   B1<=30;  B2<=27;  B3<=24;

        //--------------------------------------------------------
        // Cycle 5
        //--------------------------------------------------------
        @(posedge clk);
        A0<=0;   A1<=0;   A2<=12;  A3<=15;
        B0<=0;   B1<=0;   B2<=31;  B3<=28;

        //--------------------------------------------------------
        // Cycle 6
        //--------------------------------------------------------
        @(posedge clk);
        A0<=0;   A1<=0;   A2<=0;   A3<=16;
        B0<=0;   B1<=0;   B2<=0;   B3<=32;

        //--------------------------------------------------------
        // Flush
        //--------------------------------------------------------
        repeat(8)
        begin
            @(posedge clk);
            A0<=0; A1<=0; A2<=0; A3<=0;
            B0<=0; B1<=0; B2<=0; B3<=0;
        end

        #20;

        $display("");
        $display("==============================================");
        $display("Result Matrix");
        $display("==============================================");

        $display("%d %d %d %d",sum00,sum01,sum02,sum03);
        $display("%d %d %d %d",sum10,sum11,sum12,sum13);
        $display("%d %d %d %d",sum20,sum21,sum22,sum23);
        $display("%d %d %d %d",sum30,sum31,sum32,sum33);

        $display("==============================================");

        $finish;

    end

endmodule